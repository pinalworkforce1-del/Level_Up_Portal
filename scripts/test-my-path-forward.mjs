import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(p,'utf8');
const app=read('public/career-tree-next/my-path-forward/app.js');
const html=read('public/career-tree-next/my-path-forward/index.html');
const intro=read('public/career-tree-next/discover-me/index.html');
const discover=read('public/career-tree-next/discover-me/app.js');
const sync=read('public/career-tree-sync.js');
const fields=app.match(/\{id:'[^']+',group:'(reflection|vision|plan)'/g)||[];
assert.equal(fields.length,11,'Expected all 11 non-sensitive Mind Map reflection fields');
assert.match(app,/id:'nextChapter'/);
assert.match(app,/id:'resources'/);
assert.match(app,/id:'futureVision'/);
assert.match(app,/id:'readiness'|readiness:null/);
assert.doesNotMatch(app,/id:'barriers'|id:'housing'|id:'health'|id:'legal'|id:'currentWage'/i,
  'Sensitive barrier/current income questions must not be collected');
assert.equal((html.match(/id="coachConversation"/g)||[]).length,1,'One private-conversation checkbox');
assert.doesNotMatch(html,/name="(?:barrier|housing|health|legal)"|id="coachDetails"/i,'No barrier details controls');
assert.match(app,/next\.coachConversation=data\.coachConversation===true;/,'Save only checkbox boolean');
assert.match(app,/Number\.isInteger\(data\.readiness\)/,'Readiness remains optional numeric');
assert.match(html,/class="example"/,'Examples available alongside prompts');
assert.match(app,/document\.createElement\('details'\)/,'Every field receives Show me an example');
assert.match(app,/const allowed=regionOkay&&completed;/,'Pinal plus completed O*NET required');
assert.match(app,/saved on this device|Saved on this device/,'Local save fallback included');
assert.match(app,/LevelUpCareerTreeSync\.save\(MODULE_ID/,'Cloud sync supported');
assert.match(sync,/'my-path-forward'/,'Cloud sync module ID enabled');
assert.match(intro,/id="myPathInvitation" hidden/,'Optional link shown only when eligible');
assert.match(discover,/function showOptionalPinalPath\(\)/,'Discover Me results honor Pinal');
assert.match(intro,/Continue to Explore Careers/,'Existing direct Explore Careers progression kept');
assert.match(html,/You don't need to share personal details here/,'Private conversation wording present');
console.log('My Path Forward static privacy, optional gating, example, and saving checks passed.');

assert.match(app,/worksheetMiddle/,'Worksheet grid sections present');
assert.match(app,/worksheetChapter/,'Next Chapter banner present');
assert.match(app,/worksheetPlan/,'Five-part action row present');
assert.match(app,/readinessLevels/,'Readiness bands present');
assert.match(app,/state\.coachConversation\?'☑ I would like to talk privately/,'Only private conversation checkbox is surfaced');
assert.doesNotMatch(app,/\{id:'barriers'/,'Do not collect sensitive barriers');
const css=read('public/career-tree-next/my-path-forward/styles.css');
assert.match(css,/@page\{size:letter landscape/,'Landscape letter worksheet PDF layout');
